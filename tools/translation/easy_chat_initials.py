#!/usr/bin/env python3
"""Sort the Easy Chat words of a translation for the word picker's ABC mode.

usage: easy_chat_initials.py LANG OUT_H

The ABC mode lists the words by initial, A to Z and then the rest, in the order
of src/easy_chat_menu.c's sECMenuInitialList00-26, which follow the English
spelling. This writes the same 27 lists for the words as translated in
files/msgdata/LANG/ (English where a row is not translated), for
easy_chat_menu.c to include in a translation build.

Words spelled the same are listed once: as in the English lists, 0xFFFE and a
count introduce them, and the menu shows the first one the player knows.
"""
import os
import re
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tl import ROOT, Bank  # noqa: E402

GROUPS = 27  # A-Z, then everything else


def read(path):
    return open(os.path.join(ROOT, path), encoding='utf-8').read()


def word_banks():
    """The (bank stem, first word id) of each Easy Chat group, from src/easy_chat.c."""
    banks = re.search(r'sNarcMsgBanks\[EC_GROUP_MAX\] = \{(.*?)\};', read('src/easy_chat.c'), re.S).group(1)
    stems = re.findall(r'NARC_msg_(msg_\d{4})_bin', banks)
    mins = [int(n) for n in re.findall(r'#define EC_WORDS_\w+_MIN\s+\((\d+)\)', read('include/constants/easy_chat.h'))]
    assert len(stems) == len(mins), (stems, mins)
    return list(zip(stems, mins))


def sort_key(text):
    text = text.upper().replace('Œ', 'OE').replace('Æ', 'AE')
    text = ''.join(c for c in unicodedata.normalize('NFD', text) if not unicodedata.combining(c))
    return re.sub(r'[^A-Z0-9 ]', '', text), text


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    lang, out_path = sys.argv[1:]
    lists = re.findall(r'static const u16 sECMenuInitialList(\d\d)\[\] = \{(.*?)\};', read('src/easy_chat_menu.c'), re.S)
    assert [int(n) for n, _ in lists] == list(range(GROUPS)), 'unexpected sECMenuInitialList arrays'
    words = [int(w, 16) for _, body in lists for w in re.findall(r'0x([0-9A-Fa-f]{4})', body)]
    words = [w for i, w in enumerate(words) if w < 0xFFFE and words[i - 1] != 0xFFFE]  # drop group counts

    banks = word_banks()
    texts = {}
    for stem, first in banks:
        bank = Bank(os.path.join(ROOT, 'files/msgdata/msg', stem + '.gmm'), lang)
        for index, english in bank.rows.items():
            texts[first + index] = bank.translated.get(index, english)

    spellings = {}
    for word in words:
        spellings.setdefault(texts[word], []).append(word)
    groups = [[] for _ in range(GROUPS)]
    for text, same in spellings.items():
        key = sort_key(text)
        initial = key[0][:1]
        groups[ord(initial) - ord('A') if 'A' <= initial <= 'Z' else GROUPS - 1].append((key, same))

    out = [f'// Generated by tools/translation/easy_chat_initials.py from files/msgdata/{lang}/: the',
           '// words of sECMenuInitialList00-26, grouped and sorted by their translated spelling.']
    for n, group in enumerate(groups):
        out.append(f'static const u16 sECMenuInitialList{n:02d}[] = {{')
        for _, same in sorted(group):
            if len(same) > 1:
                out.append(f'    0xFFFE,\n    0x{len(same):04X},')
            out.extend(f'    0x{word:04X},' for word in same)
        out.append('    0xFFFF,')
        out.append('};')
        out.append('')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
